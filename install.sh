#!/usr/bin/env bash
# Install polyglot's Python environment and select the best Whisper backend.
#
#   rocm   AMD GPU with ROCm. Reuses the distro's ROCm PyTorch packages
#          (Arch: python-pytorch-rocm, python-torchaudio-rocm, python-triton)
#          through a --system-site-packages venv, so the venv never shadows
#          the ROCm build with CPU wheels.
#   cuda   NVIDIA GPU. Installs CUDA wheels into an isolated venv with
#          `uv pip install --torch-backend=auto`.
#   cpu    No GPU. OpenVINO still uses an Intel GPU/NPU at runtime when the
#          runtime reports one.
#
# A 'polyglot' launcher is written to ~/.local/bin (or $XDG_BIN_HOME, or
# --bin-dir); pass --no-launcher to skip it.
#
# Usage: ./install.sh [--device auto|rocm|cuda|cpu] [--check]
#                     [--install-system] [--verify-model] [--model NAME]
#                     [--bin-dir DIR] [--no-launcher]
set -euo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
cd "$ROOT"

DEVICE=auto
CHECK_ONLY=0
INSTALL_SYSTEM=0
VERIFY_MODEL=0
INSTALL_LAUNCHER=1
MODEL=${POLYGLOT_MODEL:-turbo}
BIN_DIR=${XDG_BIN_HOME:-$HOME/.local/bin}
LAUNCHER_MARKER="# generated by polyglot install.sh"

BASE_PYTHON=${POLYGLOT_PYTHON:-/usr/bin/python3.14}
[ -x "$BASE_PYTHON" ] || BASE_PYTHON=$(command -v python3.14 2>/dev/null || true)

log() { printf '==> %s\n' "$*"; }
warn() { printf 'warning: %s\n' "$*" >&2; }
die() { printf 'error: %s\n' "$*" >&2; exit 1; }

usage() {
    # Print the header comment block, without the shebang.
    awk 'NR == 1 { next } /^#/ { sub(/^# ?/, ""); print; next } { exit }' "${BASH_SOURCE[0]}"
}

while [ $# -gt 0 ]; do
    case $1 in
        --device) DEVICE=${2:-}; shift 2 ;;
        --check) CHECK_ONLY=1; shift ;;
        --install-system) INSTALL_SYSTEM=1; shift ;;
        --verify-model) VERIFY_MODEL=1; shift ;;
        --model) MODEL=${2:-}; shift 2 ;;
        --bin-dir) BIN_DIR=${2:-}; shift 2 ;;
        --no-launcher) INSTALL_LAUNCHER=0; shift ;;
        -h|--help) usage; exit 0 ;;
        *) die "unknown option: $1 (try --help)" ;;
    esac
done

case $DEVICE in
    auto|rocm|cuda|cpu) ;;
    *) die "--device must be auto, rocm, cuda, or cpu" ;;
esac

[ -n "$BASE_PYTHON" ] || die "Python 3.14 not found (set POLYGLOT_PYTHON)"
"$BASE_PYTHON" -c 'import sys; sys.exit(0 if sys.version_info[:2] == (3, 14) else 1)' \
    || die "$BASE_PYTHON is not Python 3.14"
command -v uv >/dev/null 2>&1 \
    || die "uv not found: https://docs.astral.sh/uv/getting-started/installation/"

# ---------------------------------------------------------------------------
# Hardware detection
# ---------------------------------------------------------------------------

has_amd_gpu() {
    # /dev/kfd plus a gfx target means the ROCm kernel driver is usable.
    [ -e /dev/kfd ] || return 1
    command -v rocminfo >/dev/null 2>&1 || return 1
    local info
    info=$(rocminfo 2>/dev/null) || return 1
    grep -q 'gfx[0-9]' <<<"$info"
}

amd_gpu_name() {
    local names
    names=$(rocminfo 2>/dev/null | sed -n 's/^ *Marketing Name: *//p')
    if grep -Eqi 'radeon|instinct|firepro' <<<"$names"; then
        grep -Ei 'radeon|instinct|firepro' <<<"$names" | head -1
    else
        head -1 <<<"$names"
    fi
}

has_nvidia_gpu() {
    command -v nvidia-smi >/dev/null 2>&1 || return 1
    local list
    list=$(nvidia-smi -L 2>/dev/null) || return 1
    grep -q '^GPU' <<<"$list"
}

# Report the ROCm stack visible to the base interpreter. Exits non-zero when
# it is missing or cannot see a device, and prints the reason.
system_rocm_report() {
    "$BASE_PYTHON" - 2>&1 <<'PY'
import sys

parts = []
try:
    import torch
except Exception as exc:  # noqa: BLE001 - reported to the caller
    sys.exit(f"torch import failed: {exc}")
parts.append(f"torch {torch.__version__}")
parts.append(f"hip={torch.version.hip}")
parts.append(f"cuda={torch.cuda.is_available()}")
try:
    import torchaudio

    parts.append(f"torchaudio {torchaudio.__version__}")
except Exception as exc:  # noqa: BLE001
    sys.exit("; ".join(parts) + f" | torchaudio import failed: {exc}")
try:
    import triton

    parts.append(f"triton {triton.__version__}")
except Exception as exc:  # noqa: BLE001
    sys.exit("; ".join(parts) + f" | triton import failed: {exc}")
ok = bool(torch.version.hip) and torch.cuda.is_available()
print("; ".join(parts))
sys.exit(0 if ok else 1)
PY
}

resolve_device() {
    case $DEVICE in
        rocm|cuda|cpu) printf '%s\n' "$DEVICE"; return ;;
    esac
    if has_amd_gpu; then
        printf 'rocm\n'
        return
    fi
    if has_nvidia_gpu; then
        printf 'cuda\n'
        return
    fi
    printf 'cpu\n'
}

# ---------------------------------------------------------------------------
# Environment setup
# ---------------------------------------------------------------------------

venv_has_system_site() {
    grep -q '^include-system-site-packages = true' .venv/pyvenv.cfg 2>/dev/null
}

ensure_venv() {
    # $1 = system (sees distro packages) or isolated
    local want=isolated
    [ "$1" = system ] && want=system

    if [ -f .venv/pyvenv.cfg ]; then
        if { [ "$want" = system ] && ! venv_has_system_site; } ||
           { [ "$want" = isolated ] && venv_has_system_site; }; then
            log "Recreating .venv as a $want environment"
            rm -rf .venv
        fi
    fi
    if [ ! -f .venv/pyvenv.cfg ]; then
        log "Creating .venv ($want)"
        if [ "$want" = system ]; then
            uv venv --system-site-packages --python "$BASE_PYTHON"
        else
            uv venv --python "$BASE_PYTHON"
        fi
    fi
}

# The excluded packages must come from the system: a CPU torch shadows the
# ROCm build, and the locked triton fails AMD kernel compilation with
# "PassManager::run failed", which silently demotes the app to OpenVINO CPU.
prune_shadowed_rocm() {
    local site=.venv/lib/python3.14/site-packages
    [ -d "$site" ] || return 0
    local path
    for path in "$site"/torch "$site"/torchaudio "$site"/triton \
                "$site"/torch-*.dist-info "$site"/torchaudio-*.dist-info \
                "$site"/triton-*.dist-info; do
        [ -e "$path" ] || continue
        log "Removing $(basename "$path") from .venv (it shadows the system ROCm build)"
        rm -rf "$path"
    done
}

sync_system_rocm() {
    uv sync --no-install-package torch --no-install-package torchaudio \
        --no-install-package triton
}

install_system_rocm() {
    if [ "$INSTALL_SYSTEM" -ne 1 ]; then
        cat >&2 <<'EOF'
error: the ROCm PyTorch stack is not available to the base interpreter.

Install it with:
  sudo pacman -S --needed python-pytorch-rocm python-torchaudio-rocm python-triton

Then re-run ./install.sh (or pass --install-system to run pacman here).
EOF
        exit 1
    fi
    command -v pacman >/dev/null 2>&1 \
        || die "--install-system only knows pacman; install ROCm PyTorch manually"
    log "Installing ROCm PyTorch packages"
    sudo pacman -S --needed --noconfirm \
        python-pytorch-rocm python-torchaudio-rocm python-triton
}

# ---------------------------------------------------------------------------
# Verification
# ---------------------------------------------------------------------------

verify_runtime() {
    # $1 = rocm | cuda | cpu
    # Triton inspects the source of @jit functions, so the probe runs from a
    # real file rather than stdin.
    local probe status
    probe=$(mktemp "${TMPDIR:-/tmp}/polyglot-verify-XXXXXX.py")
    cat >"$probe" <<'PY'
import sys
import time

mode = sys.argv[1]
import torch

print(f"torch {torch.__version__} | hip={torch.version.hip} | cuda={torch.cuda.is_available()}")

if mode in ("rocm", "cuda"):
    label = "ROCm" if mode == "rocm" else "CUDA"
    if not torch.version.hip and mode == "rocm":
        sys.exit("torch is not a ROCm build")
    if torch.version.hip and mode == "cuda":
        sys.exit("torch is a ROCm build, not CUDA")
    if not torch.cuda.is_available():
        sys.exit(f"{label} requested, but no device is visible to torch")
    name = torch.cuda.get_device_name(0)
    x = torch.randn(2048, 2048, device="cuda", dtype=torch.float16)
    start = time.perf_counter()
    y = x @ x
    torch.cuda.synchronize()
    elapsed = (time.perf_counter() - start) * 1000
    if not torch.isfinite(y).all():
        sys.exit("GPU matmul returned non-finite values")
    print(f"{label} device: {name} | fp16 matmul 2048x2048 in {elapsed:.0f} ms")

    torch.nn.functional.layer_norm(x.float(), (2048,))
    torch.cuda.synchronize()

    # Whisper's warmup compiles Triton kernels on ROCm/CUDA. A triton that
    # does not match the torch build fails here instead of at first speech.
    import triton
    import triton.language as tl

    @triton.jit
    def _add(a, b, out, n, BLOCK: tl.constexpr):
        off = tl.program_id(0) * BLOCK + tl.arange(0, BLOCK)
        mask = off < n
        tl.store(
            out + off,
            tl.load(a + off, mask=mask) + tl.load(b + off, mask=mask),
            mask=mask,
        )

    n = 1 << 16
    a = torch.randn(n, device="cuda")
    b = torch.randn(n, device="cuda")
    out = torch.empty_like(a)
    _add[(triton.cdiv(n, 256),)](a, b, out, n, BLOCK=256)
    torch.cuda.synchronize()
    if not torch.allclose(out, a + b):
        sys.exit("triton kernel result mismatch")
    print(f"triton {triton.__version__}: kernel compiled and matched torch")
else:
    try:
        import openvino as ov

        print("OpenVINO devices:", ov.Core().available_devices)
    except Exception as exc:  # noqa: BLE001 - informational only
        print(f"OpenVINO unavailable: {exc}")
    if torch.cuda.is_available():
        print("note: torch sees a GPU but the CPU profile was selected")
PY
    if .venv/bin/python "$probe" "$1"; then
        status=0
    else
        status=$?
    fi
    rm -f "$probe"
    return "$status"
}

verify_model() {
    log "Loading Whisper '$MODEL' through the application's own selection"
    .venv/bin/python - "$MODEL" <<'PY'
import sys

from inference_backend import load_whisper, torch_devices

print("PyTorch candidates:", torch_devices())
model, name = load_whisper(sys.argv[1])
print(f"Whisper loaded — {name} (fp16={model.inference_fp16})")
PY
}

install_launcher() {
    [ "$INSTALL_LAUNCHER" -eq 1 ] || return 0
    local target="$BIN_DIR/polyglot"
    mkdir -p "$BIN_DIR"
    if [ -e "$target" ] && ! grep -qF "$LAUNCHER_MARKER" "$target" 2>/dev/null; then
        warn "$target exists and was not created by install.sh; leaving it alone"
        return 0
    fi
    cat >"$target" <<EOF
#!/bin/sh
$LAUNCHER_MARKER
# Refresh with $ROOT/install.sh after moving the checkout.
exec "$ROOT/.venv/bin/python" "$ROOT/app.py" "\$@"
EOF
    chmod +x "$target"
    log "Installed launcher: $target"
    case ":$PATH:" in
        *":$BIN_DIR:"*) ;;
        *) warn "$BIN_DIR is not on PATH; add it to your shell profile to run 'polyglot'" ;;
    esac
}

launcher_status() {
    local target="$BIN_DIR/polyglot"
    if [ -x "$target" ] && grep -qF "$LAUNCHER_MARKER" "$target" 2>/dev/null; then
        log "Launcher: $target"
    elif [ -e "$target" ]; then
        warn "$target exists but is not the install.sh launcher"
    else
        log "Launcher: not installed ($target)"
    fi
}

run_hint() {
    case $1 in
        rocm|cuda)
            cat <<EOF

Start the app with:
  polyglot
or directly:
  .venv/bin/python app.py 2>>/tmp/polyglot.log

Do not run 'uv sync' or 'uv run python app.py' afterwards: they reinstall the
CPU wheels and silently demote the app to OpenVINO CPU. Re-run ./install.sh
for the accelerated environment instead. 'uv run --no-sync' is safe.
EOF
            ;;
        *)
            cat <<EOF

Start the app with:
  polyglot
or directly:
  .venv/bin/python app.py 2>>/tmp/polyglot.log
EOF
            ;;
    esac
}

# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

MODE=$(resolve_device)
log "Base interpreter: $BASE_PYTHON"

if [ "$CHECK_ONLY" -eq 1 ]; then
    [ -f .venv/pyvenv.cfg ] || die ".venv does not exist yet; run ./install.sh"
    case $MODE in
        rocm)
            if report=$(system_rocm_report); then
                log "System ROCm stack: $report"
            else
                log "System ROCm stack incomplete: $report"
            fi
            ;;
        cuda) log "NVIDIA GPU detected: $(nvidia-smi -L | head -1)" ;;
        cpu) log "No usable GPU detected; OpenVINO may still use Intel NPU/GPU" ;;
    esac
    log "Verifying the existing .venv"
    verify_runtime "$MODE"
    launcher_status
    if [ "$VERIFY_MODEL" -eq 1 ]; then
        verify_model
    fi
    exit 0
fi

case $MODE in
    rocm)
        [ "$(uname -s)" = Linux ] || die "ROCm support requires Linux"
        has_amd_gpu || die "no AMD GPU with a working ROCm runtime (install rocm-hip-sdk so rocminfo lists a gfx target, or use --device cpu)"
        if ! report=$(system_rocm_report); then
            warn "AMD GPU detected ($(amd_gpu_name)), but the ROCm stack is incomplete"
            warn "reported: $report"
            install_system_rocm
            report=$(system_rocm_report) || die "ROCm stack still unusable: $report"
        fi
        log "AMD GPU: $(amd_gpu_name) | $report"
        ensure_venv system
        prune_shadowed_rocm
        log "Syncing dependencies (system torch/torchaudio/triton kept out of .venv)"
        sync_system_rocm
        ;;
    cuda)
        has_nvidia_gpu || die "no NVIDIA GPU detected (use --device cpu to force CPU)"
        log "NVIDIA GPU: $(nvidia-smi -L | head -1)"
        ensure_venv isolated
        uv sync
        log "Installing CUDA wheels"
        uv pip install --python .venv/bin/python --torch-backend=auto \
            --reinstall torch torchaudio
        ;;
    cpu)
        log "No usable GPU detected; installing the CPU environment"
        ensure_venv isolated
        uv sync
        ;;
esac

log "Verifying $MODE acceleration"
if ! verify_runtime "$MODE"; then
    if [ "$MODE" = cuda ]; then
        warn "CUDA verification failed; reverting .venv to CPU wheels so the app still runs"
        uv sync
    fi
    die "$MODE acceleration is not usable; the app falls back to OpenVINO/CPU"
fi

if [ "$VERIFY_MODEL" -eq 1 ]; then
    verify_model
fi
install_launcher
log "Ready ($MODE)"
run_hint "$MODE"
